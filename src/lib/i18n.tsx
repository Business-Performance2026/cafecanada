export type TKey = keyof typeof dict.en;

const LangContext = createContext<{
  lang: Lang;
  t: (k: TKey) => string;
  toggle: () => void;
}>({ lang: "en", t: (k) => dict.en[k], toggle: () => {} });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    const saved = localStorage.getItem("cafeqr-lang");
    return saved === "fr" ? "fr" : "en";
  });
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const toggle = () =>
    setLang((l) => {
      const next = LANG_ORDER[(LANG_ORDER.indexOf(l) + 1) % LANG_ORDER.length];
      localStorage.setItem("cafeqr-lang", next);
      return next;
    });
  const t = (k: TKey) => dict[lang][k] ?? dict.en[k];
  return <LangContext.Provider value={{ lang, t, toggle }}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);

export const langButtonLabel = (lang: Lang) => LANG_LABEL[lang];
